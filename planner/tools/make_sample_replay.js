// TEMPORARY stand-in generator (wall/obstacle blocking now uses src/core/geometry.js). Produces a replay for D's development until A's
// simulator and sim/js port exist. It applies the guide section 8 equations in a
// minimal form (range noise, RSSI, wall NLOS bias, 5% packet loss). It does NOT
// model crowds, drift, spikes or frozen readings. Seeded: same seed, same file.
//
// Usage: node tools/make_sample_replay.js [seed]   (default seed 4242)
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { DT_S } from "../src/core/constants.js";
import { rng, gauss } from "../src/core/rng.js";
import { lineOfSight } from "../src/core/geometry.js";

const here = dirname(fileURLToPath(import.meta.url));
const fx = join(here, "..", "fixtures");

// Frozen section 8 values, copied here for the stand-in only.
// Source of truth: shared/signal_model.json. Replace this file's numbers when A delivers it.
const SIG = { range_a: 0.15, range_b: 0.02, rssi_ref: -40, rssi_sigma: 2.5,
  nlos_lo: 0.5, nlos_hi: 3.0, packet_loss: 0.05 };

export function generate(venue, seed, steps = 120) {
  const r = rng(seed);
  // Waypoint loop through the venue; person speed 1.2 m/s (inside the 0.8 to 1.5 range).
  const way = [[3, 3], [8, 10], [14, 16], [24, 16], [25, 4], [14, 4], [3, 3]];
  const speed = 1.2;
  const out = [];
  let seg = 0, pos = { x: way[0][0], y: way[0][1] };
  for (let k = 0; k < steps; k++) {
    const t = Math.round(k * DT_S * 10) / 10;
    const readings = venue.anchors.map((a) => {
      const d = Math.hypot(pos.x - a.x_m, pos.y - a.y_m);
      const blocked = lineOfSight({ x: a.x_m, y: a.y_m }, pos, venue).blocked;
      const bias = blocked ? SIG.nlos_lo + (SIG.nlos_hi - SIG.nlos_lo) * r() : 0;
      const range = Math.max(0, d + gauss(r) * (SIG.range_a + SIG.range_b * d) + bias);
      const rssi = SIG.rssi_ref - 20 * Math.log10(Math.max(d, 0.5)) + gauss(r) * SIG.rssi_sigma;
      const lost = r() < SIG.packet_loss;
      return {
        anchor_id: a.anchor_id,
        range_m: lost ? null : +range.toFixed(3),
        rssi_dbm: lost ? null : +rssi.toFixed(1),
        is_nlos: blocked, bias_m: +bias.toFixed(3),
      };
    });
    out.push({ k, t, truth: { x_m: +pos.x.toFixed(3), y_m: +pos.y.toFixed(3) }, readings });
    // advance along the loop
    let remain = speed * DT_S;
    while (remain > 0 && seg < way.length - 1) {
      const tgt = { x: way[seg + 1][0], y: way[seg + 1][1] };
      const dist = Math.hypot(tgt.x - pos.x, tgt.y - pos.y);
      if (dist <= remain) { pos = tgt; remain -= dist; seg++; }
      else { pos = { x: pos.x + ((tgt.x - pos.x) / dist) * remain, y: pos.y + ((tgt.y - pos.y) / dist) * remain }; remain = 0; }
    }
  }
  return {
    schema_version: "1.0",
    stand_in: true,
    scenario_id: "standin_office_walk",
    run_id: null,
    venue_id: venue.venue_id,
    dt_s: DT_S,
    seed,
    caveats: [
      "Temporary stand-in generated by planner/tools/make_sample_replay.js.",
      "Simulated data. No crowd, drift, spike or frozen-reading effects.",
      "Replace with A's replay fixtures through scenario_adapter.js.",
    ],
    steps: out,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const seed = Number(process.argv[2] ?? 4242);
  const venue = JSON.parse(readFileSync(join(fx, "venue_office_standin.json"), "utf8"));
  const replay = generate(venue, seed);
  const text = JSON.stringify(replay) + "\n";
  writeFileSync(join(fx, "replay_office_standin.json"), text);
  let commit = "unknown";
  try { commit = execSync("git rev-parse HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch {}
  writeFileSync(join(fx, "replay_office_standin.manifest.json"), JSON.stringify({
    script: "tools/make_sample_replay.js", seed, steps: replay.steps.length,
    config: SIG, config_hash: createHash("sha256").update(JSON.stringify(SIG)).digest("hex"),
    node: process.version, git_commit: commit, date: new Date().toISOString(),
  }, null, 2) + "\n");
  console.log(`Wrote replay (${replay.steps.length} steps, seed ${seed}).`);
}
